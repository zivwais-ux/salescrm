#!/usr/bin/env python3
"""
Turn the parsed PDF reports into the app's seed data.

Writes:
  web/data/dataset.js    - seeds the browser's local mode (a plain script so the
                           app also runs straight from the filesystem)
  web/data/dataset.json  - the same payload for any other tooling
  db/seed.sql            - the same data as INSERTs for Supabase
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from parse_pdf import parse  # noqa: E402


def sql_str(value):
    return "'" + value.replace("'", "''") + "'"


def build(sources):
    parties, sales, agents = {}, [], {}
    for path, year in sources:
        rows, _ = parse(path, year)
        for row in rows:
            agents[row["agent_no"]] = row["agent_name"]
            for no, name in ((row["customer_no"], row["customer_name"]),
                             (row["payer_no"], row["payer_name"])):
                if name and (no not in parties or len(name) > len(parties[no])):
                    parties[no] = name
            for month, amount in row["months"].items():
                if amount:
                    sales.append({
                        "c": row["customer_no"], "p": row["payer_no"],
                        "y": year, "m": int(month), "a": round(amount, 2),
                        "agent": row["agent_no"],
                    })
    return agents, parties, sales


def main():
    uploads = sys.argv[1]
    sources = [(os.path.join(uploads, "fcfd7b82-2025_________.pdf"), 2025),
               (os.path.join(uploads, "8024f4f3-2026___________.pdf"), 2026)]
    agents, parties, sales = build(sources)

    years = sorted({s["y"] for s in sales})
    dataset = {
        "generated_from": "GADOT ניתוח מכירות (ת.משלוח) - מחירים",
        "agents": [{"no": no, "name": name} for no, name in sorted(agents.items())],
        "parties": [{"no": no, "name": name} for no, name in sorted(parties.items())],
        "sales": sales,
        "years": years,
        "last_closed_month": {str(y): max(s["m"] for s in sales if s["y"] == y) for y in years},
    }
    data_dir = os.path.join(ROOT, "web", "data")
    os.makedirs(data_dir, exist_ok=True)
    payload = json.dumps(dataset, ensure_ascii=False, separators=(",", ":"))
    with open(os.path.join(data_dir, "dataset.json"), "w", encoding="utf-8") as fh:
        fh.write(payload)
    with open(os.path.join(data_dir, "dataset.js"), "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/build_dataset.py - do not edit by hand.\n")
        fh.write("window.GADOT_DATASET = " + payload + ";\n")

    lines = ["-- Generated by tools/build_dataset.py from the GADOT sales reports.",
             "-- Safe to re-run: every statement is idempotent.", "",
             "begin;", ""]
    lines.append("insert into agents (agent_no, name) values")
    lines.append(",\n".join(f"  ({sql_str(no)}, {sql_str(name)})" for no, name in sorted(agents.items()))
                 + "\non conflict (agent_no) do update set name = excluded.name;")
    lines.append("")
    lines.append("insert into parties (party_no, name) values")
    lines.append(",\n".join(f"  ({sql_str(no)}, {sql_str(name)})" for no, name in sorted(parties.items()))
                 + "\non conflict (party_no) do update set name = excluded.name;")
    lines.append("")
    lines.append("insert into sales (customer_no, payer_no, agent_no, year, month, amount) values")
    lines.append(",\n".join(
        f"  ({sql_str(s['c'])}, {sql_str(s['p'])}, {sql_str(s['agent'])}, {s['y']}, {s['m']}, {s['a']})"
        for s in sales) + "\non conflict (customer_no, payer_no, agent_no, year, month) do update set amount = excluded.amount;")
    lines += ["", "commit;", ""]
    with open(os.path.join(ROOT, "db", "seed.sql"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print(f"parties={len(parties)} sales={len(sales)} years={years} "
          f"total={sum(s['a'] for s in sales):,.2f}")


if __name__ == "__main__":
    main()
